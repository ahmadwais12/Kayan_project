function pushField(entries, entity, entityId, field, value) {
  if (!entityId || !value) return;
  if (!value.fa && !value.ps) return;
  entries.push({ entity, entityId, field, fa: value.fa, ps: value.ps });
}

export async function seedTranslations(prisma) {
  const entries = [];
  const push = (entity, entityId, field, value) => pushField(entries, entity, entityId, field, value);

  for (const [key, value] of Object.entries(SETTINGS)) push("setting", key, "value", value);

  const sections = await prisma.homepageSection.findMany();
  const sectionsByKey = new Map(sections.map((row) => [row.key, row]));
  for (const [key, fields] of Object.entries(HOMEPAGE)) {
    const row = sectionsByKey.get(key);
    if (!row) continue;
    for (const [field, value] of Object.entries(fields)) push("homepage", row.id, field, value);
  }

  const navigation = await prisma.navigationItem.findMany();
  const navigationByKey = new Map(navigation.map((row) => [`${row.location}:${row.url}`, row]));
  for (const [key, value] of Object.entries(NAVIGATION)) {
    const row = navigationByKey.get(key);
    if (row) push("navigation", row.id, "label", value);
  }

  for (const [title, value] of Object.entries(WHY_ITEMS)) {
    const row = await prisma.whyChooseItem.findFirst({ where: { title } });
    if (!row) continue;
    push("whyChoose", row.id, "title", value);
    push("whyChoose", row.id, "description", WHY_DESCRIPTIONS[title]);
  }

  for (const [title, fields] of Object.entries(PROCESS_STEPS)) {
    const row = await prisma.processStep.findFirst({ where: { title } });
    if (!row) continue;
    push("processStep", row.id, "title", fields.title);
    push("processStep", row.id, "description", fields.description);
  }

  for (const [title, fields] of Object.entries(CORE_VALUES)) {
    const row = await prisma.coreValue.findFirst({ where: { title } });
    if (!row) continue;
    push("coreValue", row.id, "title", fields.title);
    push("coreValue", row.id, "description", fields.description);
  }

  for (const [label, value] of Object.entries(STATISTICS)) {
    const row = await prisma.companyStatistic.findFirst({ where: { label } });
    if (row) push("statistic", row.id, "label", value);
  }

  for (const [slug, name] of Object.entries(PROJECT_CATEGORIES)) {
    const row = await prisma.projectCategory.findUnique({ where: { slug } });
    if (row) push("projectCategory", row.id, "name", name);
  }

  for (const [slug, name] of Object.entries(SERVICE_CATEGORIES)) {
    const row = await prisma.serviceCategory.findUnique({ where: { slug } });
    if (row) push("serviceCategory", row.id, "name", name);
  }

  for (const [slug, name] of Object.entries(DEPARTMENTS)) {
    const row = await prisma.department.findUnique({ where: { slug } });
    if (row) push("department", row.id, "name", name);
  }

  for (const [slug, copy] of Object.entries(SERVICES)) {
    const row = await prisma.service.findUnique({
      where: { slug },
      include: { features: { orderBy: { sortOrder: "asc" } } },
    });
    if (!row) continue;
    for (const locale of ["fa", "ps"]) {
      const text = copy[locale];
      push("service", row.id, "title", { [locale]: text.title });
      push("service", row.id, "shortDescription", { [locale]: text.shortDescription });
      push("service", row.id, "description", { [locale]: text.description });
      row.features.forEach((feature, index) => {
        const title = text.features[index];
        if (title) push("serviceFeature", feature.id, "title", { [locale]: title });
      });
    }
  }

  for (const [slug, copy] of Object.entries(PROJECTS)) {
    const row = await prisma.project.findUnique({ where: { slug } });
    if (!row) continue;
    for (const locale of ["fa", "ps"]) {
      const text = copy[locale];
      push("project", row.id, "title", { [locale]: text.title });
      push("project", row.id, "location", { [locale]: text.location });
      push("project", row.id, "description", { [locale]: text.description });
    }
  }

  const specifications = await prisma.projectSpecification.findMany();
  for (const row of specifications) {
    const copy = PROJECT_SPECIFICATIONS[row.label];
    if (!copy) continue;
    push("projectSpecification", row.id, "label", copy.label);
    push("projectSpecification", row.id, "value", copy.value);
  }

  for (const [slug, name] of Object.entries(FAQ_CATEGORIES)) {
    const row = await prisma.faqCategory.findUnique({ where: { slug } });
    if (row) push("faqCategory", row.id, "name", name);
  }

  for (const [question, copy] of Object.entries(FAQS)) {
    const row = await prisma.fAQ.findFirst({ where: { question } });
    if (!row) continue;
    for (const locale of ["fa", "ps"]) {
      push("faq", row.id, "question", { [locale]: copy[locale].question });
      push("faq", row.id, "answer", { [locale]: copy[locale].answer });
    }
  }

  for (const [slug, name] of Object.entries(GALLERY_CATEGORIES)) {
    const row = await prisma.galleryCategory.findUnique({ where: { slug } });
    if (row) push("galleryCategory", row.id, "name", name);
  }

  const media = await prisma.galleryMedia.findMany();
  for (const row of media) {
    const copy = GALLERY_MEDIA[row.url];
    if (copy) push("galleryMedia", row.id, "title", copy);
  }

  for (const [slug, name] of Object.entries(BLOG_CATEGORIES)) {
    const row = await prisma.blogCategory.findUnique({ where: { slug } });
    if (row) push("blogCategory", row.id, "name", name);
  }

  for (const [slug, name] of Object.entries(BLOG_TAGS)) {
    const row = await prisma.blogTag.findUnique({ where: { slug } });
    if (row) push("blogTag", row.id, "name", name);
  }

  for (const [slug, copy] of Object.entries(BLOG_POSTS)) {
    const row = await prisma.blogPost.findUnique({ where: { slug } });
    if (!row) continue;
    for (const locale of ["fa", "ps"]) {
      const text = copy[locale];
      push("blog", row.id, "title", { [locale]: text.title });
      push("blog", row.id, "excerpt", { [locale]: text.excerpt });
      push("blog", row.id, "content", { [locale]: text.content });
    }
  }

  const footerRows = await prisma.footerSetting.findMany();
  for (const row of footerRows) {
    const copy = FOOTER_SETTINGS[row.key];
    if (copy) push("footerSetting", row.key, "value", copy);
  }

  let written = 0;
  const batchSize = 25;
  for (let index = 0; index < entries.length; index += batchSize) {
    const batch = entries.slice(index, index + batchSize);
    await Promise.all(
      batch.flatMap((entry) =>
        ["fa", "ps"]
          .filter((locale) => entry[locale])
          .map((locale) =>
            prisma.translation.upsert({
              where: {
                locale_entity_entityId_field: {
                  locale,
                  entity: entry.entity,
                  entityId: entry.entityId,
                  field: entry.field,
                },
              },
              update: { value: entry[locale] },
              create: {
                locale,
                entity: entry.entity,
                entityId: entry.entityId,
                field: entry.field,
                value: entry[locale],
              },
            }),
          ),
      ),
    );
    written += batch.filter((entry) => entry.fa).length + batch.filter((entry) => entry.ps).length;
  }

  return {
    fields: entries.length,
    rows: written,
    entities: new Set(entries.map((entry) => entry.entity)).size,
  };
}
